"""Обновляет читалку в desktop/dist под свежую сборку.

Файл лежит рядом с артефактами и уходит в релиз, поэтому правится скриптом: так в нём
не остаётся старых номеров версии и старых описаний отчёта.
"""
import pathlib

p = pathlib.Path(__file__).resolve().parent.parent / "dist" / "README.txt"
text = p.read_text(encoding="utf-8")

REPL = [
    ("iohub-desktop_0.3.0_x64-setup.exe", "iohub-desktop_0.4.0_x64-setup.exe"),
    ("iohub-desktop-0.3.0-portable.zip", "iohub-desktop-0.4.0-portable.zip"),
    ("""Кнопка «Сообщить об ошибке» (в английской версии — «Report a problem») открывает
панель с уже собранным отчётом: версия программы, система, подключённые
устройства, последние строки журнала и то, что вы напишете сами. Оттуда можно
отправить письмо на iohub@aspidov.ru, открыть задачу на
https://github.com/aspidovss/iohub/issues или сохранить отчёт файлом в папку
%APPDATA%\\vision.io.hub.desktop\\reports\\ .

Из отчёта убирается имя пользователя из путей, серийный номер сокращается до
последних трёх знаков. Прочитайте текст перед отправкой — отправка происходит
только по вашей кнопке.""",
     """Кнопка «Сообщить об ошибке» (в английской версии — «Report a problem») открывает
панель с уже собранным отчётом. У отчёта есть номер вида HUB-20261119-2CA14D0F:
он выдаётся при каждом открытии панели, попадает в тему письма и в заголовок
задачи на GitHub, а имя файла отчёта кончается теми же восемью символами.
Внутри — версия программы и версия интерфейса, система, язык, экран,
подключённые устройства, последние строки журнала и короткий список того, что
вы нажимали перед обращением (последние 60 нажатий, только подписи кнопок).
Оттуда можно отправить письмо на iohub@aspidov.ru, открыть задачу на
https://github.com/aspidovss/iohub/issues или сохранить отчёт файлом в папку
%APPDATA%\\vision.io.hub.desktop\\reports\\ .

Из отчёта убирается имя пользователя из путей, серийный номер сокращается до
последних трёх знаков; введённый вами текст, раскладка и настройки клавиатуры
в него не попадают. Прочитайте текст перед отправкой — отправка происходит
только по вашей кнопке."""),
    ("Собрано: 19 ноября 2026, версия 0.3.0", "Собрано: 20 ноября 2026, версия 0.4.0"),
]

missing = []
for old, new in REPL:
    if old in text:
        text = text.replace(old, new)
    elif new not in text:
        missing.append(old.splitlines()[0])

FOOT = """Внизу экрана настроек
---------------------
Программа напоминает о себе строкой под настройками: iohub-desktop, её версия,
версия интерфейса и ссылки на страницу проекта и на отчёт об ошибке. Знак бренда
из шапки убран при сборке — остался только текст названия.

"""
if "Внизу экрана настроек" not in text:
    anchor = "Если что-то не работает\n-----------------------"
    text = text.replace(anchor, FOOT + anchor)

p.write_text(text, encoding="utf-8")
print("обновлено:", p)
for m in missing:
    print("НЕ НАЙДЕНО:", m)
